/* Chrome QA against the explicit local fixture. Authentication emails and AI are simulated.
 * The backend validates signed ES256 tokens and uses the normal ownership repository.
 */
import { createRequire } from "node:module";
import assert from "node:assert/strict";
import fs from "node:fs";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || "playwright");
const base = process.env.E2E_URL || "http://127.0.0.1:3036";
const screenshots = new URL("../../docs/screenshots/", import.meta.url).pathname;
fs.mkdirSync(screenshots, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--no-sandbox"] });
const errors = [];
const results = [];

async function signup(page, email) {
  await page.goto(`${base}/cadastro`);
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Senha", { exact: true }).fill("test-password-1234");
  await page.getByLabel("Tenho 18 anos").check();
  await page.getByLabel("Li e aceito").check();
  await page.getByRole("button", { name: "Criar conta gratuita" }).click();
  await page.waitForURL("**/verificar");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Código de confirmação").fill("123456");
  await page.getByRole("button", { name: "Confirmar código", exact: true }).click();
  await page.waitForURL("**/dashboard");
  await page.getByRole("button", { name: "Estudo", exact: true }).click();
  await page.getByRole("button", { name: "Gerar e estudar" }).waitFor();
}

try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: "reduce" });
  const page = await desktop.newPage();
  page.on("pageerror", error => errors.push(error.message));
  const calls = [];
  page.on("request", req => { if (new URL(req.url()).pathname.startsWith("/api/")) calls.push(req.url()); });
  await page.goto(base);
  await page.getByRole("heading", { level: 1, name: /Aprenda de verdade/ }).waitFor();
  assert.equal(calls.length, 0);
  await page.screenshot({ path: `${screenshots}public-home-desktop.png`, fullPage: true });
  await page.getByRole("link", { name: "Ver como funciona" }).click();
  assert.equal(new URL(page.url()).hash, "#como-funciona");
  await page.locator("summary").filter({ hasText: "Como a IA encontra as respostas?" }).click();
  await page.getByText(/O DevMind recupera trechos do catálogo/).waitFor({ state: "visible" });
  results.push("Public homepage, anchors, FAQ and zero API requests");
  await page.goto(`${base}/dashboard`);
  await page.waitForURL("**/entrar?retomar=1");
  await page.getByRole("button", { name: "Entrar na minha conta" }).waitFor({ state: "visible" });
  results.push("Server-side private-route redirect");
  const emailA = `qa-a-${Date.now()}@example.com`;
  await signup(page, emailA);
  await page.setViewportSize({ width: 1440, height: 1000 });
  const cookies = await desktop.cookies();
  assert.ok(cookies.find(c => c.name === "devmind_access")?.httpOnly);
  assert.ok(cookies.find(c => c.name === "devmind_refresh")?.httpOnly);
  assert.ok(!(await page.evaluate(() => JSON.stringify(localStorage))).includes("access_token"));
  await page.getByLabel("Tema", { exact: true }).selectOption("git");
  await page.getByLabel("Quantidade", { exact: true }).selectOption("1");
  await page.getByText(/Catálogo local · \d+ documentos/).waitFor();
  await page.screenshot({ path: `${screenshots}public-study-panel.png`, fullPage: true });
  await page.getByRole("button", { name: "Gerar e estudar" }).click();
  await page.getByLabel("Explique com suas palavras").fill("git restore --staged README.md preserva as edições locais.");
  await page.getByRole("button", { name: "Avaliar resposta", exact: true }).click();
  await page.getByRole("heading", { name: "Conceito compreendido" }).waitFor();
  await page.getByRole("button", { name: "Lembrei Avançar uma etapa", exact: true }).click();
  await page.getByText("Próxima revisão:", { exact: false }).waitFor();
  await page.screenshot({ path: `${screenshots}public-study-feedback.png`, fullPage: true });
  const a = await page.evaluate(async () => (await fetch("/api/learning/progress")).json());
  assert.equal(a.total, 1); assert.equal(a.attempts, 1);
  const aCard = await page.evaluate(async () => (await fetch("/api/learning/progress")).json());
  results.push("Signup, email-code confirmation, HttpOnly session, generation, evaluation and spaced repetition");
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: "reduce" });
  const phone = await mobile.newPage();
  phone.on("pageerror", error => errors.push(error.message));
  await phone.goto(base);
  await phone.setViewportSize({ width: 320, height: 844 });
  assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await phone.setViewportSize({ width: 390, height: 844 });
  assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await phone.screenshot({ path: `${screenshots}public-home-mobile.png`, fullPage: true });
  await signup(phone, `qa-b-${Date.now()}@example.com`);
  assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  const b = await phone.evaluate(async () => (await fetch("/api/learning/progress")).json());
  assert.equal(b.total, 0); assert.equal(b.attempts, 0);
  await phone.screenshot({ path: `${screenshots}public-dashboard-mobile.png`, fullPage: true });
  results.push("Mobile layout and separate account B with empty progress");
  await page.getByRole("button", { name: "Sair", exact: true }).click();
  await page.waitForURL(base + "/");
  assert.equal((await desktop.cookies()).filter(c => c.name.startsWith("devmind_")).length, 0);
  await page.goto(`${base}/entrar`);
  await page.getByLabel("Email", { exact: true }).fill(emailA);
  await page.getByLabel("Senha", { exact: true }).fill("test-password-1234");
  await page.getByRole("button", { name: "Entrar na minha conta" }).click();
  await page.waitForURL("**/dashboard");
  const restored = await page.evaluate(async () => (await fetch("/api/learning/progress")).json());
  assert.equal(restored.total, aCard.total); assert.equal(restored.attempts, 1);
  // Remove only the short-lived cookie, retaining the HttpOnly refresh session.
  const access = (await desktop.cookies()).find(c => c.name === "devmind_access");
  await desktop.addCookies([{ ...access, value: "", expires: 1 }]);
  await page.reload();
  await page.waitForURL("**/dashboard");
  await page.getByRole("button", { name: "Estudo", exact: true }).waitFor();
  results.push("Logout, login, persistent progress and expired-access session refresh");
  const otherTab = await desktop.newPage();
  await otherTab.goto(`${base}/dashboard`);
  await otherTab.getByRole("button", { name: "Sair", exact: true }).waitFor();
  await page.getByRole("button", { name: "Sair", exact: true }).click();
  await page.waitForURL(base + "/");
  await otherTab.waitForURL("**/entrar?retomar=1");
  results.push("Logout invalidates the other open dashboard tab");
  await otherTab.close();
  await phone.getByRole("button", { name: "Sair", exact: true }).click();
  await phone.goto(`${base}/recuperar`);
  await phone.getByLabel("Email", { exact: true }).fill(emailA);
  await phone.getByRole("button", { name: "Enviar código de recuperação" }).click();
  await phone.getByRole("status").waitFor();
  await phone.goto(`${base}/verificar`);
  await phone.getByLabel("Email", { exact: true }).fill(emailA);
  await phone.getByLabel("Código de confirmação").fill("123456");
  await phone.getByLabel("Estou recuperando minha senha").check();
  await phone.getByRole("button", { name: "Confirmar código", exact: true }).click();
  await phone.waitForURL("**/nova-senha");
  await phone.getByLabel("Senha", { exact: true }).fill("new-test-password-1234");
  await phone.getByRole("button", { name: "Salvar nova senha" }).click();
  await phone.waitForURL("**/entrar?senha=atualizada");
  results.push("Recovery-code flow and password-change UX with simulated Supabase");
  assert.deepEqual(errors, []);
  fs.writeFileSync(new URL("../../evaluation/public-browser-local.json", import.meta.url), JSON.stringify({ passed: true, mode: "Chrome desktop and mobile, simulated Supabase and AI, real signed JWT and database", results, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, results, errors }));
  await desktop.close(); await mobile.close();
} finally { await browser.close(); }
